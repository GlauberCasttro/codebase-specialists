def resolve_target(arg=None):
    """Raiz do alvo (realpath). arg > $CLAUDE_PROJECT_DIR > cwd."""
    raw = arg or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    root = os.path.realpath(os.path.expanduser(raw))
    if not os.path.isdir(root):
        raise CsError("alvo não é um diretório: %s" % raw,
                      "passe --target <repo> apontando para a raiz do repositório")
    return root


